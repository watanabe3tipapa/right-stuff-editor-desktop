interface TemplateStore {
  templates: DocumentTemplate[];
  loaded: boolean;
  ensureBuiltin: () => Promise<void>;
  load: () => Promise<void>;
  add: (input: {
    name: string;
    description: string;
    content: string;
    category?: string;
  }) => Promise<DocumentTemplate>;
  remove: (id: string) => Promise<void>;
  update: (id: string, input: {
    name?: string;
    description?: string;
    content?: string;
    category?: string;
  }) => Promise<void>;
}

const generateId = () => crypto.randomUUID();

export const useTemplateStore = create<TemplateStore>()((set, get) => ({
  templates: [],
  loaded: false,

  ensureBuiltin: async () => {
    const all = (await desktop.templatesList()) as Array<{
      uuid: string;
      builtin: boolean;
    }>;
    const builtinIds = new Set(BUILTIN_TEMPLATES.map((b) => b.id));

    const obsolete = all.filter((a) => a.builtin && !builtinIds.has(a.uuid));
    for (const item of obsolete) {
      await desktop.templatesDelete(item.uuid);
    }

    const remaining = all.filter((a) => !obsolete.includes(a));
    const missing = BUILTIN_TEMPLATES.filter((b) =>
      remaining.every((a) => a.uuid !== b.id),
    );
    for (const b of missing) {
      await desktop.templatesUpsert({
        uuid: b.id,
        name: b.name,
        description: b.description,
        content: b.content,
        category: b.category,
        builtin: true,
        createdAt: b.createdAt.toISOString(),
        updatedAt: b.updatedAt.toISOString(),
      });
    }
  },

  load: async () => {
    await get().ensureBuiltin();
    const rows = (await desktop.templatesList()) as Array<{
      uuid: string;
      name: string;
      description: string;
      content: string;
      category: string | null;
      builtin: number;
      createdAt: string;
      updatedAt: string;
    }>;
    const templates: DocumentTemplate[] = rows.map((row) => ({
      id: row.uuid,
      name: row.name,
      description: row.description,
      content: row.content,
      category: row.category ?? undefined,
      builtin: !!row.builtin,
      createdAt: new Date(row.createdAt),
      updatedAt: new Date(row.updatedAt),
    }));
    set({ templates, loaded: true });
  },

  add: async (input) => {
    const now = new Date();
    const tmpl: DocumentTemplate = {
      id: generateId(),
      name: input.name,
      description: input.description,
      content: input.content,
      category: input.category,
      builtin: false,
      createdAt: now,
      updatedAt: now,
    };
    await desktop.templatesUpsert({
      uuid: tmpl.id,
      name: tmpl.name,
      description: tmpl.description,
      content: tmpl.content,
      category: tmpl.category,
      builtin: false,
      createdAt: now.toISOString(),
      updatedAt: now.toISOString(),
    });
    set((state) => ({ templates: [...state.templates, tmpl] }));
    return tmpl;
  },

  remove: async (id) => {
    await desktop.templatesDelete(id);
    set((state) => ({ templates: state.templates.filter((t) => t.id !== id) }));
  },

  update: async (id, input) => {
    const now = new Date();
    const existing = get().templates.find((t) => t.id === id);
    if (!existing) return;
    await desktop.templatesUpsert({
      uuid: id,
      name: input.name ?? existing.name,
      description: input.description ?? existing.description,
      content: input.content ?? existing.content,
      category: input.category ?? existing.category,
      builtin: existing.builtin,
      createdAt: existing.createdAt.toISOString(),
      updatedAt: now.toISOString(),
    });
    set((state) => ({
      templates: state.templates.map((t) =>
        t.id === id
          ? {
              ...t,
              name: input.name ?? t.name,
              description: input.description ?? t.description,
              content: input.content ?? t.content,
              category: input.category ?? t.category,
              updatedAt: now,
            }
          : t,
      ),
    }));
  },
}));

export default useTemplateStore;
