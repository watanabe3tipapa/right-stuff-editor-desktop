import { desktop } from "./desktop";
import { markdownToHtml } from "./markdown";

export interface FileInfo {
  name: string;
  path?: string;
  content: string;
}

export interface SaveResult {
  success: boolean;
  filePath?: string;
  error?: string;
}

export interface OpenResult {
  success: boolean;
  file?: FileInfo;
  error?: string;
}

let activeFileName: string | null = null;
let activeFilePath: string | null = null;

export const getActiveFileInfo = (): {
  name: string | null;
  path: string | null;
  hasHandle: boolean;
} => ({
  name: activeFileName,
  path: activeFilePath,
  hasHandle: !!activeFilePath,
});

export const setActiveFile = (name: string | null, path: string | null) => {
  activeFileName = name;
  activeFilePath = path;
  if (typeof window !== "undefined") {
    window.dispatchEvent(
      new CustomEvent("local-file-changed", { detail: { name, hasHandle: !!path } }),
    );
  }
};

export const clearActiveFileHandle = () => {
  activeFileName = null;
  activeFilePath = null;
};

export const hasActiveFile = (): boolean => !!activeFilePath;

export const saveToActiveFile = async (content: string): Promise<SaveResult> => {
  if (!activeFilePath) return { success: false, error: "No active file" };
  try {
    await desktop.fileWrite(activeFilePath, content);
    return { success: true, filePath: activeFilePath };
  } catch (error) {
    return { success: false, error: (error as Error).message };
  }
};

export const openFile = async (): Promise<OpenResult> => {
  try {
    const path = await tiny.dialog.openFile({ types: ["md", "markdown", "txt"] });
    if (!path) return { success: false, error: "Cancelled" };
    const file = await desktop.fileRead(path);
    setActiveFile(file.name, file.path);
    return { success: true, file };
  } catch (error) {
    return { success: false, error: (error as Error).message };
  }
};

async function writeDialog(
  content: string,
  suggestedName: string,
  types: string[],
): Promise<SaveResult> {
  try {
    const path = await tiny.dialog.saveFile({ name: suggestedName, types });
    if (!path) return { success: false, error: "Cancelled" };
    await desktop.fileWrite(path, content);
    const name = path.split("/").pop() ?? suggestedName;
    setActiveFile(name, path);
    return { success: true, filePath: path };
  } catch (error) {
    return { success: false, error: (error as Error).message };
  }
}

export const saveFile = async (
  content: string,
  suggestedName: string = "document.md",
): Promise<SaveResult> => {
  return writeDialog(content, suggestedName, ["md"]);
};

export const exportAsHtml = async (
  htmlContent: string,
  suggestedName: string = "document.html",
): Promise<SaveResult> => {
  return writeDialog(htmlContent, suggestedName, ["html"]);
};

export const exportAsTxt = async (
  content: string,
  suggestedName: string = "document",
): Promise<SaveResult> => {
  return writeDialog(content, `${suggestedName}.txt`, ["txt"]);
};

export const exportAsJson = async (
  content: string,
  suggestedName: string = "document.json",
): Promise<SaveResult> => {
  const jsonContent = JSON.stringify(
    { content, exportedAt: new Date().toISOString() },
    null,
    2,
  );
  return writeDialog(jsonContent, suggestedName, ["json"]);
};

export const exportAsDocx = async (
  content: string,
  suggestedName: string = "document.doc",
): Promise<SaveResult> => {
  const htmlContent = await markdownToHtml(content);
  const docxContent = `<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word" xmlns="http://www.w3.org/TR/REC-html40">
<head><meta charset="utf-8"><title>${suggestedName}</title></head>
<body>${htmlContent}</body></html>`;
  return writeDialog(docxContent, suggestedName, ["doc"]);
};

export const exportAsModelfile = async (
  _content: string,
  suggestedName: string = "Modelfile",
): Promise<SaveResult> => {
  const modelfileContent = `# Modelfile generated by Right-Stuff Editor Desktop
# Created: ${new Date().toISOString()}

FROM gemma4:e4b

PARAMETER temperature 0.15
PARAMETER seed 2026
PARAMETER num_ctx 8192
PARAMETER repeat_penalty 1.25
PARAMETER top_k 20
PARAMETER top_p 0.4
`;
  return writeDialog(modelfileContent, suggestedName, ["txt"]);
};

export const exportAsPdf = async (
  htmlContent: string,
  suggestedName: string = "document.pdf",
): Promise<SaveResult> => {
  const printWindow = window.open("", "_blank");
  if (!printWindow) {
    return {
      success: false,
      error: "PDF 出力は印刷ダイアログから行ってください",
    };
  }
  printWindow.document.write(`<!doctype html><html><head><title>${suggestedName}</title>
<style>body{font-family:system-ui,-apple-system,sans-serif;padding:40px;max-width:800px;margin:0 auto}@media print{body{padding:0}}</style>
</head><body>${htmlContent}</body></html>`);
  printWindow.document.close();
  printWindow.focus();
  setTimeout(() => printWindow.print(), 250);
  return { success: true, filePath: suggestedName };
};

